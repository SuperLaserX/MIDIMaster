// V-Synth XT VC-2 patch files (.p02): the user patches on the XT's internal drive,
// V:\Internal.vc2\Patch\nnn <name>.p02, which a computer reads and writes in USB storage mode.
//
// A file is 5060 bytes: a 32-byte header (the same in every file: "VC20Rev008", chunk "PATa" "VC_2",
// 13A4h bytes) and a bit-packed patch of 5028 bytes. The packing is the V-Synth's (.p00) with 8 zones:
// the VC-2 keeps its values in V-Synth fields where it has them (the algorithm in Patch Category,
// carrier tone in zone 0, modulator tone in zone 1) and its additions in extension areas. Where each
// editor value lies is VC2_MAP (generated by tools/roland/vc2_map.mjs, checked on all 208 values of the
// 16 factory patches against the unit's SysEx answers). Encodings:
//   raw      the SysEx value (multi-nibble values as their whole value, e.g. effect parameters + 32768)
//   shift    the SysEx value less the firmware's shift
//   oct12    carrier OSC 1 Pitch Octave Shift: stored as the coarse tune, (v - 64) * 12 + 64
//   p32768   growl intensity and speed: the value + 32768 in 16 bits
//   mod46    modulator OSC Wave: (v + 46) mod 128
// The VC-2 does not show 85 bits of the carrier zone (V-Synth OSC type, wave gain, analog waveform,
// wave number, start offset and time trip, which differ between factory files as leftovers) nor the
// other zones; a written file takes them from the factory patch 001 "LargeChoir 1".

import { VC2_MAP, P02_HEADER, P02_TEMPLATE } from './roland-vsynthxt-vc2-map.js';

export const P02_SIZE = 5060;

function getBits(buf, pos, bp, w) {
  let v = 0;
  for (let j = 0; j < w; j++) {
    const bit = pos * 8 + bp + j;
    v = v * 2 + ((buf[bit >> 3] >> (7 - (bit & 7))) & 1);
  }
  return v;
}
function setBits(buf, pos, bp, w, v) {
  for (let j = w - 1; j >= 0; j--) {
    const bit = pos * 8 + bp + j;
    const mask = 1 << (7 - (bit & 7));
    buf[bit >> 3] = (v % 2) ? buf[bit >> 3] | mask : buf[bit >> 3] & ~mask;
    v = Math.floor(v / 2);
  }
}
const fromB64 = (s) => (typeof atob === 'function' ? Uint8Array.from(atob(s), (c) => c.charCodeAt(0)) : Uint8Array.from(Buffer.from(s, 'base64')));
let template = null;

// SysEx value -> stored value, and back
const ENC = {
  raw: [(v) => v, (s) => s],
  shift: [(v, m) => v - m.shift, (s, m) => s + m.shift],
  oct12: [(v) => (v - 64) * 12 + 64, (s) => Math.round((s - 64) / 12) + 64],
  p32768: [(v) => v + 32768, (s) => s - 32768],
  mod46: [(v) => (v + 46) % 128, (s) => (s + 82) % 128],
};

export function isP02(bytes) {
  return bytes?.length >= P02_SIZE && P02_HEADER.every((x, i) => bytes[i] === x);
}

const readValue = (d, p) => { let v = 0; for (let k = 0; k < (p.nibbles || 1); k++) v = (p.nibbles ? v * 16 : 0) + d[p.offset + k]; return v; };
function writeValue(d, p, v) {
  if (p.nibbles) { for (let k = p.nibbles - 1; k >= 0; k--) { d[p.offset + k] = v & 15; v = Math.floor(v / 16); } } else d[p.offset] = v;
}

/** The editor's patch data (SysEx layout) from a .p02 file, on top of `base` (the patch defaults). */
export function readP02(bytes, params, base) {
  if (!isP02(bytes)) return null;
  const pay = bytes.subarray(0x20, P02_SIZE);
  const d = Uint8Array.from(base);
  for (const p of params) {
    const m = VC2_MAP[p.key];
    if (!m) continue;
    const v = ENC[m.enc][1](getBits(pay, m.pos, m.bp, m.w), m);
    writeValue(d, p, Math.max(0, Math.min(p.nibbles ? 16 ** p.nibbles - 1 : 127, v)));
  }
  return d;
}

/** A .p02 file from the editor's patch data. */
export function writeP02(d, params) {
  template ??= fromB64(P02_TEMPLATE);
  const out = new Uint8Array(P02_SIZE);
  out.set(P02_HEADER);
  out.set(template, 0x20);
  const pay = out.subarray(0x20);
  for (const p of params) {
    const m = VC2_MAP[p.key];
    if (!m) continue;
    const v = ENC[m.enc][0](readValue(d, p), m);
    setBits(pay, m.pos, m.bp, m.w, ((v % 2 ** m.w) + 2 ** m.w) % 2 ** m.w);
  }
  return out;
}

/** "nnn Name.p02", the name the XT gives VC-2 user patch n (1-448). */
export const p02FileName = (n, name) => `${String(n).padStart(3, '0')} ${String(name).trimEnd().replace(/[\\/:*?"<>|]/g, '_')}.p02`;
