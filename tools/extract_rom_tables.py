"""Extract display/conversion tables from a K2000 v3.87 OS EPROM pair.

Usage:
    python -I tools/extract_rom_tables.py <HIGH eprom> <LOW eprom> js/model/romtables.js

The HIGH chip holds the even (most significant) bytes of each 16-bit word.
The OS image is linked at 0x100000. Table addresses were located by
k2kremote and confirmed in this project against firmware v3.87J.
"""
import json
import sys

BASE = 0x100000

TABLES = {
    # name: (address, count, signed, description)
    "lfoRateCentiHz": (0x1FB404, 256, False, "LFO rate, raw unsigned byte -> 1/100 Hz"),
    "filterCoarseHz": (0x1FC204, 128, False, "DSP frequency, (signed semitone + 48) -> Hz"),
    "envFilFreqCents": (0x1F9604, 256, True, "ENV2->frequency depth, (signed byte + 128) -> cents"),
    "lfoPitchCents": (0x1FA204, 256, True, "LFO->pitch depth, (signed byte + 128) -> cents"),
    "envTimeMs": (0x1FBA04, 256, False, "Envelope/ASR time, raw byte -> milliseconds"),
}


def main():
    hi_path, lo_path, out_path = sys.argv[1:4]
    hi = open(hi_path, "rb").read()
    lo = open(lo_path, "rb").read()
    if len(hi) != len(lo):
        raise SystemExit("EPROM images differ in size")
    image = bytearray(len(hi) * 2)
    image[0::2] = hi
    image[1::2] = lo

    result = {}
    for name, (addr, count, signed, _desc) in TABLES.items():
        off = addr - BASE
        vals = [int.from_bytes(image[off + 2 * i: off + 2 * i + 2], "big", signed=signed) for i in range(count)]
        result[name] = vals

    lines = [
        "// Generated by tools/extract_rom_tables.py from the K2000 OS EPROMs. Do not edit.",
        "// Source addresses (OS linked at 0x100000):",
    ]
    for name, (addr, count, _s, desc) in TABLES.items():
        lines.append(f"//   {name}: 0x{addr:06X} x{count} - {desc}")
    for name, vals in result.items():
        lines.append(f"export const {name} = {json.dumps(vals, separators=(',', ':'))};")
    open(out_path, "w", newline="\n").write("\n".join(lines) + "\n")
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
