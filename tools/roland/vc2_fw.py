"""Generate js/devices/defs/roland-vsynthxt-vc2-lists.js: the VC-2 (Vocal Designer) screen lists.

The VC-2 application (VAPP2, os.4.50001C.bin unpacked by vsynth_rom.py, loaded at 0x89300000)
answers its own SysEx model 00 00 0D with a parameter map of its own (Setup 12 bytes, System 145,
Sampling Templates 8 x 29, patch Common 331, Carrier 67, Modulator 15, Vocoder 14), built at run
time from descriptors, so the parameter rows come from the VC-2 MIDI implementation. This script
takes the value names those rows display from the VC-2's own screen strings, found by content:
algorithms, MFX, chorus and reverb types, formant styles and types, vibrato types, the controller
lists. Effect parameters use the framework tables in roland-vsynthxt-vc2-fw.js (vsynth_fw.py).

Usage: python -I vc2_fw.py <os.4 image> <out .js>
"""
import json
import re
import struct
import sys

BASE = 0x89300000
b = open(sys.argv[1], 'rb').read()
N_WORDS = len(b) // 4
WORDS = struct.unpack('<%dI' % N_WORDS, b[:N_WORDS * 4])


def cstr(p, maxlen=64):
    if not BASE <= p < BASE + len(b):
        return None
    o = p - BASE
    e = b.find(b'\x00', o, o + maxlen)
    if e < o:
        return None
    s = b[o:e]
    return s.decode('latin1') if all(32 <= c < 127 or c == 10 for c in s) else None


def ptr_list(first, count, last=None):
    """The `count` strings of the pointer table whose first entries read `first` (blanks ignored)."""
    for i in range(N_WORDS - count):
        if all((cstr(WORDS[i + k]) or '\x00').strip() == x for k, x in enumerate(first)):
            out = [(cstr(WORDS[i + k]) or '').strip() for k in range(count)]
            if last is None or out[-1] == last:
                return out
    raise SystemExit(f'pointer table {first} ... {last} not found')


def str_run(first, count):
    """`count` NUL-terminated strings stored one after another from `first` (padding skipped)."""
    o = b.find(first.encode('latin1') + b'\x00')
    if o < 0:
        o = b.find(first.encode('latin1') + b' ')
    if o < 0:
        raise SystemExit(f'string {first!r} not found')
    out = []
    p = o
    for _ in range(count):
        e = b.index(b'\x00', p)
        out.append(b[p:e].decode('latin1').strip())
        p = e + 1
        while b[p] == 0:
            p += 1
    return out


def unnumber(lst):
    return [re.sub(r'^\d+:', '', x).strip() for x in lst]


L = {}
L['algorithm'] = [x.replace('\n', ' ') for x in str_run('Modeling\nChoir', 12)]
assert L['algorithm'][-1] == 'Process Type2', L['algorithm']
L['mfx'] = unnumber(str_run('00:Thru', 42))
assert L['mfx'][-1] == 'Pseudo Stereo', L['mfx']
L['chorus'] = ['Off'] + unnumber(str_run('01:Chorus 1', 8))  # 0 is OFF (no screen string of its own)
assert L['chorus'][-1] == 'Fbk Short Delay', L['chorus']
L['reverb'] = ['Off'] + str_run('Stereo Plate', 17)
assert L['reverb'][-1] == 'Delay', L['reverb']
def runs(anchor, count):
    """Every run of `count` strings that starts with the string `anchor`."""
    out = []
    for m in re.finditer(re.escape(anchor.encode('latin1')) + rb' *\x00', b):
        lst = []
        p = m.start()
        for _ in range(count):
            e = b.index(b'\x00', p)
            lst.append(b[p:e].decode('latin1').strip())
            p = e + 1
            while b[p] == 0:
                p += 1
        out.append(unnumber(lst))
    return out


# two lists start with 00:FLAT: the carrier formant styles (FLAT, OPERA ... IMPROV) and the vocoder
# formant types (FLAT, HARD ... STFEM2)
L['formantStyle'] = next(r for r in runs('00:FLAT', 11) if r[1] == 'OPERA')
assert L['formantStyle'][-1] == 'IMPROV', L['formantStyle']
L['formantType'] = next(r for r in runs('00:FLAT', 16) if r[1] == 'HARD')
assert L['formantType'][-1] == 'STFEM2', L['formantType']
L['vibratoType'] = ptr_list(['NORMAL', 'FEMALE1', 'FEMALE2', 'MALE'], 4)
L['control'] = ptr_list(['OFF', 'CC01', 'CC02'], 110, 'BREATH')  # 0-109
# indexed by CC number: 0 OFF, 1-31, 32 shows OFF, 33-95, then BEND ... BREATH (96-109)
assert L['control'][32] == 'OFF' and L['control'][33] == 'CC33' and L['control'][96] == 'BEND', L['control']
# the system assign lists (beam, pad, trip, knobs, pedals): the same CC slots, then BEND-UP, BEND-DOWN, AFT
tail = ['BEND-UP', 'BEND-DOWN', 'AFT']
# the firmware's display spec of these assigns ends ... CC33 (02) CC95 (01) BEND-UP (01) BEND-DOWN (01) AFT
assert b'\x01BEND-UP\x01BEND-DOWN\x01AFT\x00' in b, 'assign list tail'
L['assign'] = L['control'][:96] + tail

with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/roland/vc2_fw.py from the V-Synth XT VC-2 application (os.4.50001C.bin).\n')
    f.write('// Do not edit by hand: re-run the generator.\n')
    f.write(f'export const LISTS = {json.dumps(L, ensure_ascii=False)};\n')
print({k: len(v) for k, v in L.items()})
print(L['algorithm'], L['reverb'], L['vibratoType'])
