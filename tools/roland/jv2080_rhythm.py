"""Rhythm sets the JV-2080 can put on part 10: the preset sets in its flash and the sets on the
SR-JV80 expansion boards. Writes js/devices/defs/roland-jv2080-rhythm.js.

Preset rhythm sets (v1.02 flash image). The rhythm count function (0x0E12467E, a jump table by
patch group) points each preset group at a descriptor [u8 count, .., u32 data]: PR-A 0x0E060620,
PR-B 0x0E060630, PR-C 0x0E060640, PR-D 0x0E060650, PR-E 0x0E061B88, and 0x0E060660 for the
factory contents of the two user sets. Each set is the JV-2080's packed rhythm format: 2699 bytes =
an 11-byte name (12 seven-bit characters) and 64 notes (keys 35-98) of 42 bytes. A parameter is
read as in the getter 0x0E127388: the little-endian 16-bit word at the descriptor's byte, masked and
shifted ([u16 mask][byte][shift][default][min][max][0] at 0x0E058100, IDs 0x23B-0x246 for the name
and 0x24B-0x284 for a note, the SysEx byte order).

Expansion boards. The board loader (0x0E13779C) reads the header of each board: byte 0x54 gives
the rhythm set format, 2 = JV-80 format (61 notes of 44 bytes, no name; struct +0x1E) or 4 = the
JV-2080's own format (named, struct +0x20); u16 at 0x68 is the count, u32 at 0x90 the table. A
JV-80 format set gets the name "JV rhythm" when the JV-2080 converts it (0x0E126C88 writes
'J','V',' ','r','h','y','t','h','m'); a set in the JV-2080 format carries its name.

usage: python3 -I jv2080_rhythm.py <jv2080_v102.bin> <folder with jvNN.uns board images> <out.js>
           [<folder with Roland's "PrX Rhythm 001-002 (via User).syx" dumps> to check the decode]
"""
import glob
import json
import os
import re
import struct
import sys

BASE = 0x0E000000
DESC = 0x058100
SET_SIZE = 11 + 64 * 42
GROUPS = [('PR-A', 0x0E060620), ('PR-B', 0x0E060630), ('PR-C', 0x0E060640), ('PR-D', 0x0E060650), ('PR-E', 0x0E061B88)]
FACTORY_USER = 0x0E060660
BOARD_JV80_NAME = 'JV rhythm'


def desc(fw, gid):
    return struct.unpack('>HBB', fw[DESC + gid * 8:DESC + gid * 8 + 4])


def get(fw, rec, gid):
    mask, byte, shift = desc(fw, gid)
    word = rec[byte] | ((rec[byte + 1] << 8) if byte + 1 < len(rec) else 0)
    return (word & mask) >> shift


def group_sets(fw, ptr):
    """(count, [set bytes]) of a preset group descriptor."""
    d = ptr - BASE
    count = fw[d]
    data, = struct.unpack('>I', fw[d + 4:d + 8])
    o = data - BASE
    return [fw[o + i * SET_SIZE:o + (i + 1) * SET_SIZE] for i in range(count)]


def decode(fw, rec):
    """A packed set as SysEx bytes: name (12) and 64 notes of 58 bytes."""
    name = bytes(get(fw, rec, g) for g in range(0x23B, 0x247))
    notes = []
    for k in range(64):
        nr = rec[11 + k * 42:11 + (k + 1) * 42] + b'\0'
        notes.append(bytes(get(fw, nr, g) for g in range(0x24B, 0x285)))
    return name, notes


def board_sets(fw, path):
    rom = open(path, 'rb').read()
    fmt = rom[0x54]
    count, = struct.unpack('>H', rom[0x68:0x6A])
    table, = struct.unpack('>I', rom[0x90:0x94])
    if fmt == 4:
        # the JV-2080's own format: the packed name is the first 11 bytes of each 2699-byte set
        recs = [rom[table + i * SET_SIZE:table + (i + 1) * SET_SIZE] for i in range(count)]
        return fmt, [decode(fw, rec)[0].decode('latin-1') for rec in recs]
    return fmt, [BOARD_JV80_NAME] * count if fmt == 2 else []


def syx_sets(path):
    data = open(path, 'rb').read()
    sets = {}
    for m in re.finditer(rb'\xf0\x41.\x6a\x12(....)(.*?)(.)\xf7', data, re.S):
        a = m.group(1)
        sets.setdefault(a[1] - 0x40, {})[(a[2], a[3])] = m.group(2)
    return sets


def main():
    fw = open(sys.argv[1], 'rb').read()
    boards_dir, out = sys.argv[2], sys.argv[3]
    dumps = sys.argv[4] if len(sys.argv) > 4 else None
    presets = {}
    for g, ptr in GROUPS:
        presets[g] = [decode(fw, rec) for rec in group_sets(fw, ptr)]
    factory = [decode(fw, rec) for rec in group_sets(fw, FACTORY_USER)]
    checked = []
    if dumps:
        for g, sets in presets.items():
            files = glob.glob(os.path.join(dumps, f'*Pr{g[-1]} Rhythm*.syx'))
            if not files:
                continue
            got = syx_sets(files[0])
            for i, (name, notes) in enumerate(sets):
                body = got.get(i, {})
                same = body.get((0, 0), b'')[:12] == name and all(body.get((35 + k, 0)) == notes[k] for k in range(64))
                checked.append(f'{g} {i + 1}: {"equal" if same else "DIFFERENT"}')
        print('\n'.join(checked), file=sys.stderr)
    boards = {}
    for path in sorted(glob.glob(os.path.join(boards_dir, 'jv*.uns'))):
        num = int(re.search(r'jv(\d+)\.uns', path).group(1))
        fmt, names = board_sets(fw, path)
        boards[num] = names
        print(f'SR-JV80-{num:02d}: format {fmt}, {len(names)} rhythm sets', file=sys.stderr)
    lines = [
        '// Generated by tools/roland/jv2080_rhythm.py from the JV-2080 v1.02 flash and the SR-JV80 board ROMs. Do not edit.',
        '// Preset rhythm set names (two per preset group) as the flash holds them, the factory names of the',
        '// two user sets, and the rhythm sets on each expansion board: a set in the JV-80 format has no name',
        '// and the JV-2080 calls it "JV rhythm" (0x0E126C88); see docs/devices/roland-jv2080.md.',
        'export const PRESET_RHYTHM_SETS = {',
    ]
    for g, sets in presets.items():
        lines.append(f'  {json.dumps(g)}: {json.dumps([n.decode("latin-1") for n, _ in sets])},')
    lines.append('};')
    lines.append(f'export const FACTORY_USER_RHYTHM_SETS = {json.dumps([n.decode("latin-1") for n, _ in factory])};')
    lines.append(f'export const BOARD_JV80_RHYTHM_NAME = {json.dumps(BOARD_JV80_NAME)};')
    lines.append('/** Rhythm set names per board number (empty: the board has none). */')
    lines.append('export const BOARD_RHYTHM_SETS = {')
    for num, names in boards.items():
        lines.append(f'  {num}: {json.dumps(names)},')
    lines.append('};')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
