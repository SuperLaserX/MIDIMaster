// Write docs/devices/roland-vsynth-xt-vc2-params.md: every VC-2 parameter (address, name, values,
// size, algorithm group, firmware parameter, place in a .p02 file), what each algorithm takes, and the
// effect parameters per effect type. From the editor's definition and the generated tables
// (roland-vsynthxt-vc2-map.js, roland-vsynthxt-vc2-fw.js); wave names from
// re/vsynthxt/live/vc2_wave_names.json and the system blocks' firmware names from
// re/vsynthxt/live/vc2_descriptors.json when present.
// usage: node tools/roland/vc2_doc.mjs [out.md]

import fs from 'node:fs';
import def, { patchBuilt, sysBuilt, fxSlot, PATCH, algorithmInit } from '../../js/devices/defs/roland-vsynthxt-vc2.js';
import { VC2_MAP, ALG_GROUPS, ALG_WAVES, ALG_INIT_DIFF } from '../../js/devices/defs/roland-vsynthxt-vc2-map.js';
import { P } from '../../js/devices/defs/roland-vsynthxt-vc2-fw.js';
import { LISTS } from '../../js/devices/defs/roland-vsynthxt-vc2-lists.js';
import { readParam, formatParam } from '../../js/core/model/memmap.js';
import { intToAddr } from '../../js/core/midi/roland.js';

const OUT = process.argv[2] || 'docs/devices/roland-vsynth-xt-vc2-params.md';
const live = (f) => new URL(`../../re/vsynthxt/live/${f}`, import.meta.url);
const WAVES = fs.existsSync(live('vc2_wave_names.json')) ? new Map(JSON.parse(fs.readFileSync(live('vc2_wave_names.json'), 'utf8'))) : new Map();
const DESC = fs.existsSync(live('vc2_descriptors.json')) ? JSON.parse(fs.readFileSync(live('vc2_descriptors.json'), 'utf8')) : [];

const hex = (n) => n.toString(16).toUpperCase().padStart(2, '0');
const addr = (a) => intToAddr(a).map(hex).join(' ');
const cell = (s) => String(s).replace(/\|/g, '\\|');
const wave = (n) => (WAVES.has(n) ? `${n} ${WAVES.get(n)}` : String(n));
const waveRange = (w) => (!w ? 'locked' : w[0] === w[1] ? `${w[0]} only` : `${wave(w[0])} - ${wave(w[1])}`);

/** A value as the VC-2 shows it. */
function shown(p, v) {
  if (p.options) return p.options.find(([x]) => x === v)?.[1] ?? String(v);
  return p.format ? p.format(v) : formatParam(p, v);
}
/** The values a parameter takes, as the VC-2 shows them. */
function values(p) {
  const { min, max } = p;
  if (p.options) {
    const o = p.options;
    if (o.length <= 12) return o.map(([v, l]) => `${v} ${l}`).join(', ');
    return `${o[0][0]}-${o[o.length - 1][0]}: ${o.slice(0, 3).map(([, l]) => l).join(', ')} ... ${o[o.length - 1][1]}`;
  }
  if (p.format && min !== undefined) return `${min}-${max}: ${shown(p, min)} ... ${shown(p, max)}`;
  return `${min}-${max}`;
}
const sizeOf = (p) => (p.nibbles ? `${p.nibbles} nibbles` : '1');

const lines = [];
const out = (...l) => lines.push(...l);
out('# V-Synth XT VC-2: every parameter',
  '',
  'Generated by `node tools/roland/vc2_doc.mjs` from the editor\'s definition',
  '(`js/devices/defs/roland-vsynthxt-vc2.js`) and the tables generated from the VC-2 application',
  '(`roland-vsynthxt-vc2-fw.js`, `roland-vsynthxt-vc2-map.js`); do not edit by hand. How the tables were',
  'made is in [roland-vsynth-xt-vc2.md](roland-vsynth-xt-vc2.md).',
  '',
  'Values are SysEx values (model 00 00 0D, device ID 10h) with what the VC-2 shows for them. Values of',
  'several nibbles are sent as that many bytes of 4 bits, high nibble first. **Group** is the',
  'parameter\'s algorithm group: 0 is used by every algorithm, the others only by the algorithms that',
  'take them (below); the VC-2 silently refuses a value the patch\'s algorithm does not take.',
  '**Firmware** is the entry of the VC-2 application\'s parameter table that holds the value (id and',
  'name; the VC-2 reuses the V-Synth framework, so many keep V-Synth names: OSC1 Pan is kept in "MOD',
  'Attack Time", Glide Time in "Env 1 Decay Time"). **.p02** is where the value',
  'sits in a patch file\'s payload (after the 32-byte header): byte.bit (bit 0 = the MSB), bits, and',
  'how it is stored (see the end).',
  '');

// ------------------------------------------------------------------ algorithms
out('## Algorithms', '',
  'What each algorithm takes. Choosing an algorithm by SysEx makes the VC-2 load that',
  'algorithm\'s **INIT PATCH**, whatever patch it held: algorithm 0\'s, with the differences listed',
  '(read on the unit 2026-11-24/25). Wave numbers checked on the unit from 0 to 70 (the modulator to',
  '127); "locked": the algorithm does not use it.',
  '',
  '| # | Algorithm | Groups | Carrier OSC 1 wave | Carrier OSC 2 wave | Modulator wave | INIT PATCH (differences from algorithm 0) |',
  '|---|---|---|---|---|---|---|');
const byOffset = (o) => patchBuilt.params.find((p) => !p.get && o >= p.offset && o < p.offset + (p.nibbles || 1));
ALG_GROUPS.forEach((g, a) => {
  const d = algorithmInit(a);
  const diffs = [...new Set(ALG_INIT_DIFF[a].map(([o]) => byOffset(o)))].filter((p) => p && p.key !== 'c_0')
    .map((p) => `${p.label} ${p.key === 'ca_b' || p.key === 'ca_1b' ? wave(readParam(d, p)) : shown(p, readParam(d, p))}`);
  const w = ALG_WAVES[a];
  out(`| ${a} | ${LISTS.algorithm[a]} | 0, ${g.join(', ')} | ${waveRange(w.osc1)} | ${waveRange(w.osc2)} | ${w.mod ? `${w.mod[0]}-${w.mod[1]}` : 'locked'} | ${a === 0 ? 'the reference: name "INIT PATCH"' : cell(diffs.join('; ') || 'the same')} |`);
});
out('', '| Group | Taken by algorithms | Parameters |', '|---|---|---|');
const groups = new Map();
for (const p of patchBuilt.params) { const m = VC2_MAP[p.key]; if (m) { if (!groups.has(m.group)) groups.set(m.group, []); groups.get(m.group).push(p); } }
[...groups.keys()].sort((a, b) => a - b).forEach((g) => {
  const ps = groups.get(g);
  const algs = g === 0 ? 'all' : ALG_GROUPS.map((x, a) => (x.includes(g) ? a : null)).filter((x) => x !== null).join(', ');
  const count = (b) => ps.filter((p) => p.block === b).length;
  const names = g === 0
    ? `${ps.length} parameters, marked 0 in the tables: ${count('c')} common (algorithm, name, beam/pad, effect switches, MFX, chorus, reverb), carrier ${ps.filter((p) => p.block === 'ca').map((p) => p.label).join(', ')}, vocoder ${ps.filter((p) => p.block === 'vo').map((p) => p.label).join(', ')}`
    : ps.map((p) => `${p.block === 'mo' ? 'Modulator ' : p.block === 'vo' ? 'Vocoder ' : ''}${p.label}`).join(', ');
  out(`| ${g} | ${algs} | ${cell(names)} |`);
});
out('');

// ------------------------------------------------------------------ patch
out('## Patch', '',
  `The temporary patch is at ${addr(PATCH)}; user patch U001-U448 n (0-447) at 20 00 00 00 + n x 00 01 00 00`,
  '(the same layout). Addresses below are the temporary patch\'s.', '');
const PART_NAMES = { c: 'Common', ca: 'Carrier', mo: 'Modulator', vo: 'Vocoder' };
for (const part of patchBuilt.parts) {
  out(`### ${PART_NAMES[part.key]} (${addr(PATCH + part.at)}, ${part.size} bytes)`, '',
    '| Address | Parameter | Values | Size | Group | Firmware | .p02 |', '|---|---|---|---|---|---|---|');
  let fxRun = null;
  for (const p of patchBuilt.params.filter((x) => x.block === part.key && !x.get && x.kind !== 'char')) {
    const m = VC2_MAP[p.key];
    const fw = m ? `${hex(m.id >> 8)}${hex(m.id & 255)}h ${m.fw}` : '';
    const pos = m ? `${m.pos}.${m.bp}, ${m.w}${m.enc !== 'raw' ? `, ${m.enc}${m.shift ? ` ${m.shift}` : ''}` : ''}` : '';
    if (p.fxSlot) {
      // effect parameter slots: one row for the run
      if (fxRun?.kind === p.fxKind) { fxRun.last = p; continue; }
      fxRun = { kind: p.fxKind, first: p, last: p };
      out(`| ${addr(PATCH + p.at)} | ${p.label} ... (see Effect parameters) | -20000 - +20000 (+32768 as sent) per type | 4 nibbles each | 0 | ${fw} ... | ${pos} ... |`);
      continue;
    }
    const v = p.key === 'ca_b' || p.key === 'ca_1b' || p.key === 'mo_1' ? `${p.min}-${p.max}, per algorithm (above)` : values(p);
    out(`| ${addr(PATCH + p.at)} | ${p.label} | ${cell(v)} | ${sizeOf(p)} | ${m?.group ?? ''} | ${fw} | ${pos} |`);
  }
  if (part.key === 'c') out('', 'Patch Name 1-12 (00 00 01 - 00 00 0C): ASCII 32-127, one character each (firmware 120h-12Bh, .p02 byte 1.0 on, 7 bits each).');
  out('');
}

// ------------------------------------------------------------------ effects per type
out('## Effect parameters', '',
  'The MFX (32 slots), chorus (12) and reverb (24) parameters are numbered slots whose meaning depends on',
  'the effect type; each is 4 nibbles holding the value + 32768. The VC-2\'s screen names and value',
  'lists per type (value lists the firmware computes were taken from its display routine, emulated).', '');
for (const [kind, list, n, label] of [['mfx', LISTS.mfx, 32, 'MFX'], ['chorus', LISTS.chorus, 12, 'Chorus'], ['reverb', LISTS.reverb.slice(0, 15), 24, 'Reverb']]) {
  out(`### ${label}`, '');
  list.forEach((name, t) => {
    const slots = [];
    for (let k = 1; k <= n; k++) {
      const s = fxSlot(kind, k, t);
      if (s.hidden) continue;
      slots.push(`| ${k} | ${cell(s.label.replace(/^[^:]*:\s*/, ''))} | ${cell(values({ ...s, min: s.min ?? 0, max: s.max ?? 0 }))} |`);
    }
    if (!slots.length) { out(`**${t} ${name}**: no parameters.`, ''); return; }
    out(`**${t} ${name}**`, '', '| Slot | Parameter | Values |', '|---|---|---|', ...slots, '');
  });
}

// ------------------------------------------------------------------ system
out('## System', '',
  'Setup at 01 00 00 00, system at 02 00 00 00, sampling template n (0-7) at 03 00 0n 00 (template 1 is',
  'shown). Device ID, Tx Edit, Receive SysEx, output gain, digital output, USB mode and USB MIDI thru have no',
  'SysEx address. System values are not in patch files.', '');
const fwSys = new Map();
for (const x of DESC.filter((d) => ['su', 'sy', 't0'].includes(d.block) && d.nib === 0)) {
  const id = x.id + (x.size > 1 ? x.size - 1 : 0);
  fwSys.set(`${x.block}:${x.addr}`, P[id] ? `${hex(id >> 8)}${hex(id & 255)}h ${P[id][0]}` : '');
}
const SYS_NAMES = { su: 'Setup', sy: 'System', t0: 'Sampling template 1' };
for (const part of sysBuilt.parts.filter((p) => SYS_NAMES[p.key])) {
  out(`### ${SYS_NAMES[part.key]} (${addr(part.at)}, ${part.size} bytes)`, '', '| Address | Parameter | Values | Size | Firmware |', '|---|---|---|---|---|');
  for (const p of sysBuilt.params.filter((x) => x.block === part.key && !x.get)) {
    out(`| ${addr(p.at)} | ${cell(p.label.replace(/^Template 1 /, ''))} | ${cell(values(p))} | ${sizeOf(p)} | ${cell(fwSys.get(`${p.block}:${p.at - part.at}`) || '')} |`);
  }
  out('');
}

// ------------------------------------------------------------------ files
out('## .p02 encodings', '',
  '- **raw**: the SysEx value (values of several nibbles as their whole value).',
  '- **shift n**: the SysEx value less n.',
  '- **oct12**: carrier OSC 1 Pitch Octave Shift is kept as a coarse tune in semitones, (v - 64) x 12 + 64.',
  '- **p32768**: growl intensity and speed, the value + 32768 in 16 bits.',
  '- **mod46**: the modulator wave, (v + 46) mod 128.',
  '',
  'The VC-2 keeps its patch in the V-Synth\'s packed layout with 8 zones: the algorithm in the V-Synth\'s',
  'Patch Category, the carrier tone in zone 0 (bytes 230 on; OSC 1/2 Wave Number in 16 bits at 4996 and',
  '4998), the modulator in zone 1, the envelopes from 854, growl at 2966, beam/pad at 4054. 85 bits of',
  'the carrier zone are V-Synth tone fields the VC-2 does not show (OSC type, wave gain, analog waveform,',
  'wave number, start offset, time trip); they differ between factory files and a written file takes them',
  'from factory patch 001.',
  '');

fs.writeFileSync(OUT, lines.join('\n'));
console.log(`${lines.length} lines written to ${OUT} (${def.objects.length} objects)`);
