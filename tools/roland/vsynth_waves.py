"""Write js/devices/defs/roland-vsynthxt-waves.js: the V-Synth XT's preset wave names (1-224).

The factory internal drive (V-SynthXTDiskImage.bin inflated by vsynth_rom.py; MBR, FAT16 at the
partition the MBR names) holds one file per preset wave, Internal.prj\\Wave\\nnn <name>.w00 (36 bytes:
chunk "link" = the preset wave number, chunk "name" = the 16-character name). The names here are the
"name" chunks, so they match what the XT shows and what model 00 24 kind 4 answers.

usage: python -I vsynth_waves.py <V-SynthXTDiskImage.0.bin> <out .js>
"""
import json
import struct
import sys

img = open(sys.argv[1], 'rb').read()
lba = struct.unpack('<I', img[0x1be + 8:0x1be + 12])[0]
v = img[lba * 512:]
bps, spc = struct.unpack('<H', v[11:13])[0], v[13]
res = struct.unpack('<H', v[14:16])[0]
nfat, nroot = v[16], struct.unpack('<H', v[17:19])[0]
spf = struct.unpack('<H', v[22:24])[0]
fat = v[res * bps:(res + spf) * bps]
root = (res + nfat * spf) * bps
data = root + nroot * 32
cl = spc * bps


def chain(c):
    while 2 <= c < 0xfff8:
        yield c
        c = struct.unpack('<H', fat[2 * c:2 * c + 2])[0]


def read(c, size=None):
    d = b''.join(v[data + (k - 2) * cl:data + (k - 1) * cl] for k in chain(c))
    return d if size is None else d[:size]


def entries(raw):
    lfn = ''
    for i in range(0, len(raw), 32):
        e = raw[i:i + 32]
        if e[0] == 0:
            return
        if e[0] == 0xe5:
            lfn = ''
            continue
        if e[11] == 0x0f:
            lfn = (e[1:11] + e[14:26] + e[28:32]).decode('utf-16le', 'ignore').split('\x00')[0] + lfn
            continue
        short = e[0:8].decode('latin1').rstrip() + ('.' + e[8:11].decode('latin1').rstrip() if e[8:11].strip() else '')
        yield (lfn or short), e[11], struct.unpack('<H', e[26:28])[0], struct.unpack('<I', e[28:32])[0]
        lfn = ''


def find(path):
    raw = v[root:root + nroot * 32]
    for part in path.split('/'):
        hit = next(x for x in entries(raw) if x[0].lower() == part.lower())
        raw = read(hit[2])
    return raw


def chunks(b):
    i, out = 0, {}
    while i + 8 <= len(b):
        tag, n = b[i:i + 4].decode('latin1'), struct.unpack('<I', b[i + 4:i + 8])[0]
        out[tag] = b[i + 8:i + 8 + n]
        i += 8 + n
    return out


waves = {}
for name, attr, c, size in entries(find('Internal.prj/Wave')):
    if not name.lower().endswith('.w00'):
        continue
    ch = chunks(read(c, size))
    n = struct.unpack('<I', ch['link'][:4])[0] if len(ch.get('link', b'')) >= 4 else int(name[:3])
    waves[int(name[:3])] = (n, ch['name'].split(b'\x00')[0].decode('latin1').rstrip())
nums = sorted(waves)
assert nums == list(range(1, len(nums) + 1)), nums[:5]
names = [waves[k][1] for k in nums]
open(sys.argv[2], 'w', encoding='utf-8').write(
    '// Generated by tools/roland/vsynth_waves.py from the V-Synth XT factory drive image: the preset waves\n'
    '// (Internal.prj\\Wave\\nnn <name>.w00, "name" chunks). PRESET_WAVES[n - 1] is wave n.\n'
    f'export const PRESET_WAVES = {json.dumps(names)};\n')
print(len(names), 'preset waves:', names[:3], '...', names[-2:])
