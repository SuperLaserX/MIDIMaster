"""Dump the JV-2080 parameter descriptors (v1.02 flash image) per SysEx block.

The DT1 builder (0x0E12294C) turns an internal parameter ID into an address with the
decoder at 0x0E122554: each block is a contiguous ID range whose IDs map one to one onto
the block's byte offsets. The value getter (0x0E12B8A4) reads the descriptor table at
0x0E058100: 8 bytes per ID = [u16 mask][internal byte][shift][default][min][max][0].

usage: python3 -I jv2080_params.py <jv2080_v102.bin> [out.json]
"""
import json
import struct
import sys

BASE = 0x0E000000
TABLE = 0x0E058100

BLOCKS = [
    # key, first ID, last ID, address (temporary / edit buffer), description
    ('system', 0x000, 0x061, '00 00 00 00', 'System common'),
    ('systemScalePerform', 0x08B, 0x096, '00 00 10 00', 'System scale tune, per part (performance mode)'),
    ('systemScalePatch', 0x098, 0x0A3, '00 00 20 00', 'System scale tune (patch mode)'),
    ('performCommon', 0x0C7, 0x10A, '01 00 00 00', 'Performance common'),
    ('performPart', 0x113, 0x12C, '01 00 10 00', 'Performance part (+ part × 0x100)'),
    ('patchCommon', 0x13A, 0x183, '03 00 00 00', 'Patch common'),
    ('patchTone', 0x19F, 0x21F, '03 00 10 00', 'Patch tone (+ tone × 0x200)'),
    ('rhythmCommon', 0x23B, 0x246, '02 09 00 00', 'Rhythm set common (name)'),
    ('rhythmNote', 0x24B, 0x284, '02 09 23 00', 'Rhythm note (+ key)'),
]


def main():
    d = open(sys.argv[1], 'rb').read()
    out = {}
    for key, first, last, addr, desc in BLOCKS:
        params = []
        for gid in range(first, last + 1):
            a = TABLE - BASE + gid * 8
            mask, byte, shift, default, mn, mx = struct.unpack('>HBBBBB', d[a:a + 7])
            params.append({'offset': gid - first, 'id': gid, 'default': default, 'min': mn, 'max': mx, 'mask': mask, 'byte': byte, 'shift': shift})
        out[key] = {'address': addr, 'description': desc, 'size': last - first + 1, 'params': params}
        print(f'{key} ({desc}) at {addr}, {last - first + 1} bytes')
        for p in params:
            print(f'  {p["offset"]:02x}: default {p["default"]:3d} range {p["min"]:3d}-{p["max"]:3d}')
    if len(sys.argv) > 2:
        json.dump(out, open(sys.argv[2], 'w'), indent=1)
    if len(sys.argv) > 3:
        lines = ['// Generated by tools/roland/jv2080_params.py from the JV-2080 v1.02 flash image. Do not edit.',
                 '// Per block: address (temporary area), size, and [default, min, max] for every byte offset,',
                 '// read from the descriptor table at 0x0E058100 (8 bytes per parameter ID).', '',
                 'export const JV2080_BLOCKS = {']
        for key, b in out.items():
            ranges = ', '.join(f'[{p["default"]},{p["min"]},{p["max"]}]' for p in b['params'])
            lines.append(f'  {key}: {{ address: {json.dumps(b["address"])}, size: {b["size"]}, ranges: [{ranges}] }},')
        lines += ['};', '']
        nl = chr(10)
        open(sys.argv[3], 'w', newline=nl).write(nl.join(lines))


if __name__ == '__main__':
    main()
