# Alesis MIDIVerb 4: build js/devices/defs/alesis-midiverb4-fw.js from the v1.04 EPROM image
# (8051 code, same LCD and software family as the Wedge).
#
#   python -I tools/alesis/midiverb4_fw.py "<image .bin>" > js/devices/defs/alesis-midiverb4-fw.js
#
# What it reads (addresses in the v1.04 image):
#   3000 + 7Ch*n  32 configuration descriptors: +00h name (16 characters), +14h 4 page masks (low nibble:
#                 sliders A-D in use), +18h 4 page titles (high nibble = first character in the name, low
#                 nibble = length), +1Ch the 16 parameter maxima, +2Ch page table, +5Ch the display routine
#                 of each parameter (dispatcher CA19: A = parameter, 59h/5Ah = descriptor).
#   page table    144 bytes per page: 24-character column heading, 24-character page title ("REVERB PAGE 1
#                 PARAMETERS"), 4 long names of 24 characters.
#   DD67          128 preset programs (26 bytes each); EA67: the user bank as a reset leaves it (copy C17B).
#   display       every value of every parameter is drawn by its routine in the 8051 emulator (alesis_lcd.py):
#                 segments set AD3C / cleared AD61 / by carry AD3A, digit groups AB07, font B4BE.
#   D766 / D7BE   Util page modulator source (Mod#) and amplitude (Amp); D423 footswitch; CB68 level.
import sys, os, json
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from alesis_lcd import Lcd

DESC, STRIDE, NALG = 0x3000, 0x7C, 32
PRESETS, USER = 0xDD67, 0xEA67
SIZE = 26


def word(d, a): return (d[a] << 8) | d[a + 1]


def text_at(d, a, n): return d[a:a + n].decode('latin-1').replace(chr(0), ' ')


def main():
    d = open(sys.argv[1], 'rb').read()
    assert len(d) == 65536 and b'ALESIS MIDIVERB 4' in d, 'not a MIDIVerb 4 image'
    w = Lcd(d, font=0xB4BE, groups=0xAB07, set_=0xAD3C, clear=0xAD61, by_carry=0xAD3A, page=0x22)
    formats, fmt_index, cache, algs = [], {}, {}, []
    for n in range(NALG):
        a = DESC + STRIDE * n
        name = text_at(d, a, 16)
        masks = list(d[a + 0x14: a + 0x18])
        titles = list(d[a + 0x18: a + 0x1c])
        maxima = list(d[a + 0x1c: a + 0x2c])
        ptab = word(d, a + 0x2c)
        rtab = a + 0x5c
        pages = []
        for p in range(4):
            if not masks[p] & 15: continue
            pa = ptab + 144 * p
            head = text_at(d, pa, 24)
            t = titles[p]
            pages.append({'page': p, 'title': name[t >> 4: (t >> 4) + (t & 15)].strip(), 'sliders': masks[p] & 15,
                          'icons': masks[p] >> 4, 'heading': text_at(d, pa + 24, 24).strip(),
                          'cols': [head[6 * s: 6 * s + 6].strip() for s in range(4)],
                          'long': [text_at(d, pa + 48 + 24 * s, 24).strip() for s in range(4)]})
        fmts = []
        for i in range(16):
            mx = maxima[i]
            page = next((pg for pg in pages if pg['page'] == i // 4), None)
            if not mx or not page or not (page['sliders'] >> (i & 3)) & 1:
                fmts.append(-1); continue
            r = word(d, rtab + 2 * i)
            key = (r, mx)
            if key not in cache:
                vals = []
                for v in range(mx + 1):
                    def setup(cpu, a=a, i=i, v=v):
                        cpu.wr(0x59, a & 0xff); cpu.wr(0x5a, a >> 8)
                        cpu.x[0x22d6 + i] = v
                        cpu.a = i
                    try: vals.append(w.text(w.run(setup, 0xCA19), i & 3))
                    except Exception as e: raise RuntimeError('%s: alg %d param %d routine %04X value %d' % (e, n, i, r, v))
                k = json.dumps(vals)
                if k not in fmt_index:
                    fmt_index[k] = len(formats); formats.append({'routine': '%04X' % r, 'texts': vals})
                cache[key] = fmt_index[k]
            fmts.append(cache[key])
        algs.append({'name': name.strip(), 'pages': pages, 'max': maxima, 'fmt': fmts})

    def prog(a):
        p = d[a:a + SIZE]
        assert p[1] < NALG and all(32 <= c < 128 for c in p[2:10]), 'bad program at %04X' % a
        assert all(v <= m for v, m in zip(p[10:], algs[p[1]]['max'])), 'value above maximum at %04X' % a
        return p.hex()
    presets = [prog(PRESETS + SIZE * i) for i in range(128)]
    user = [prog(USER + SIZE * i) for i in range(128)]

    def col_texts(entry, xaddr, col, count):
        out = []
        for v in range(count):
            def s(cpu, v=v): cpu.x[xaddr] = v
            out.append(w.text(w.run(s, entry), col))
        return out
    mod_src = col_texts(0xD766, 0x2289, 0, 124)
    mod_amp = col_texts(0xD7BE, 0x229D, 1, 199)
    foot = col_texts(0xD423, 0x2288, 1, 3)
    level = col_texts(0xCB68, 0x228B, 3, 101)  # the level pages draw in column D

    js = ['// Generated by tools/alesis/midiverb4_fw.py from the Alesis MIDIVerb 4 v1.04 EPROM image.',
          '// Do not edit by hand: run the tool again. ALGORITHMS[n]: descriptor at 3000 + 7Ch n; FORMATS[f].texts[v]:',
          '// what the LCD shows for value v (the parameter\'s display routine run in an 8051 emulator).',
          'export const FIRMWARE = ' + json.dumps('MIDIVerb 4 v1.04') + ';']
    for k, v in [('ALGORITHMS', algs), ('FORMATS', formats), ('PRESETS', presets), ('USER_FACTORY', user),
                 ('MOD_SOURCES', mod_src), ('MOD_AMOUNTS', mod_amp), ('FOOTSWITCH', foot), ('LEVELS', level)]:
        js.append('export const %s = %s;' % (k, json.dumps(v, separators=(',', ':'))))
    sys.stdout.write('\n'.join(js) + '\n')


if __name__ == '__main__':
    main()
