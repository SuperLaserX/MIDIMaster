// Writes the device lists of README.md (between the <!-- devices:start --> and <!-- devices:end -->
// markers) from the project's own data:
//   - supported devices: every editor in js/devices/registry.js, grouped as on the front page
//     (js/devices/families.js), with its state from js/devices/levels.js;
//   - firmware in hand, editor not started: devices of tools/firmware/midi_devices.json that are in the
//     firmware collection and have no editor yet;
//   - waiting for firmware: the device list's devices with nothing in the collection.
// usage: node tools/readme_devices.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { DEVICES } from '../js/devices/registry.js';
import { FAMILIES, deviceFamily } from '../js/devices/families.js';
import { FULL, MISSING, isFullEditor } from '../js/devices/levels.js';

const README = new URL('../README.md', import.meta.url);
const list = JSON.parse(readFileSync(new URL('./firmware/midi_devices.json', import.meta.url), 'utf8'));

const norm = (s) => String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '');
const editors = DEVICES.filter((d) => d.hasModule || d.hasDef);
// an editor's names: the model, without its parenthesis ("Nova (desktop and Laptop)"), and each of
// several names ("DX100/DX27")
const names = (m) => { const base = String(m).replace(/\s*\(.*?\)\s*/g, ' ').trim(); return [m, base, ...base.split('/')]; };
const editorKeys = new Set(editors.flatMap((d) => names(d.model).map((m) => norm(d.maker) + norm(m))));
// lines the user put out of scope for now (with the downloads): pianos, organs, home and arranger keyboards
const OUT_OF_SCOPE = new Set(['Digital and stage pianos', 'Organs', 'Arranger and home keyboards']);

function state(d) {
  if (FULL[d.id]) return /checked on/i.test(FULL[d.id]) ? 'complete, checked on hardware' : 'complete';
  const miss = MISSING[d.id] || [];
  if (!miss.length) return 'in progress';
  return miss.every((m) => /^a hardware check/i.test(m)) ? 'complete, not yet checked on hardware' : 'in progress';
}

// supported, by family
const supported = [];
for (const f of FAMILIES) {
  const ds = editors.filter((d) => deviceFamily(d) === f.key).sort((a, b) => a.title.localeCompare(b.title));
  if (!ds.length) continue;
  supported.push(`**${f.label}**`, '');
  for (const d of ds) supported.push(`- ${d.title}: ${state(d)}`);
  supported.push('');
}

// the device list, split by whether the collection has firmware
const hasEditor = (x) => [x.model, ...(x.variants || [])].some((m) => editorKeys.has(norm(x.maker) + norm(typeof m === 'string' ? m : m?.model)));
const inScope = list.devices.filter((x) => !OUT_OF_SCOPE.has(x.category) && !hasEditor(x));
const inHand = inScope.filter((x) => Array.isArray(x.inCollection) && x.inCollection.length);
const wanted = inScope.filter((x) => !(Array.isArray(x.inCollection) && x.inCollection.length));
function byMaker(xs) {
  const m = new Map();
  for (const x of xs) { if (!m.has(x.maker)) m.set(x.maker, []); m.get(x.maker).push(x.model); }
  return [...m].sort((a, b) => a[0].localeCompare(b[0])).map(([k, v]) => `- **${k}:** ${v.sort((a, b) => a.localeCompare(b)).join(', ')}`);
}

const out = [
  '<!-- devices:start (generated by `node tools/readme_devices.mjs`; edit the data, not this list) -->',
  `### Supported (${editors.length} editors)`,
  '',
  ...supported,
  '"Not yet checked on hardware" means mapped from the firmware and tested against a simulator only.',
  '',
  `### Firmware in hand, editor not started (${inHand.length})`,
  '',
  'Every one of these gets an editor in time; until then each works as a generic MIDI device (programs, controllers, SysEx Branch Library).',
  '',
  '<details><summary>Show the list</summary>',
  '',
  ...byMaker(inHand),
  '',
  '</details>',
  '',
  `### Waiting for firmware or a ROM dump (${wanted.length})`,
  '',
  'These will be implemented once their firmware is found: an official update file, an OS disk, or a dump of the ROM chips. If you have one, it helps. (Pianos, organs and home or arranger keyboards are left out of both lists for now.)',
  '',
  '<details><summary>Show the list</summary>',
  '',
  ...byMaker(wanted),
  '',
  '</details>',
  '<!-- devices:end -->',
].join('\n');

// the status block at the top (between <!-- status:start --> and <!-- status:end -->)
const pkg = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const fullCount = editors.filter((d) => isFullEditor(d)).length;
const firmwareFiles = new Set(DEVICES.flatMap((d) => d.archives || [])).size;
const listed = list.devices.length;
const withFw = list.devices.filter((x) => Array.isArray(x.inCollection) && x.inCollection.length).length;
const status = [
  '<!-- status:start (generated by `node tools/readme_devices.mjs`) -->',
  `| | |`,
  `|---|---|`,
  `| Version | ${pkg.version} |`,
  `| Device editors | ${editors.length} (${fullCount} complete, ${editors.length - fullCount} in progress) |`,
  `| Devices in the app | ${DEVICES.length}, of which ${DEVICES.filter((d) => d.openable).length} with MIDI (every MIDI device opens at least the generic MIDI tools) |`,
  `| Firmware files behind them | ${firmwareFiles} |`,
  `| MIDI devices researched | ${listed}: firmware found for ${withFw}, still wanted for ${listed - withFw} |`,
  '<!-- status:end -->',
].join('\n');

let text = readFileSync(README, 'utf8');
{
  const s1 = text.indexOf('<!-- status:start');
  const s2 = text.indexOf('<!-- status:end -->');
  if (s1 >= 0 && s2 >= 0) text = text.slice(0, s1) + status + text.slice(s2 + '<!-- status:end -->'.length);
}
const a = text.indexOf('<!-- devices:start');
const b = text.indexOf('<!-- devices:end -->');
if (a < 0 || b < 0) throw new Error('README.md has no <!-- devices:start --> / <!-- devices:end --> markers');
writeFileSync(README, text.slice(0, a) + out + text.slice(b + '<!-- devices:end -->'.length));
console.log(`README.md: ${editors.length} editors, ${inHand.length} with firmware, ${wanted.length} waiting`);
