#!/usr/bin/env python3
"""Generate js/devices/defs/roland-system8-plugouts.js: the patch-struct tables of the PLUG-OUT engines.

Per engine:
  * its Roland Cloud plugin's Script.xml (re/system8/plugins/<name>/Script/Script.xml): the `patch` struct values
    (names, packed offsets, sizes, ranges, defaults) - the same layout as the SYSTEM-8's, other names and ranges;
  * the display tables of its region 0 image (re/system8/images/<name>_s1_region0.bin, tools/system8/region0_tables.py):
    the pages the unit shows, each value's OS parameter id (1741 = patch offset 0 ... the OS catalog numbering),
    the engine's own label when it renames a value, its range, list and display kind, and the value lists;
  * its SYNINFO model id and version (the region 0 image header).
usage: python -I tools/system8/gen_plugouts_js.py OUT.js
"""
import json, os, re, struct, sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
import region0_tables as R0  # noqa: E402

ENGINES = ['JUPITER-8', 'SH-101', 'JUNO-106', 'JX-3P', 'JUNO-60', 'JUPITER-4', 'PROMARS', 'SH-2', 'SYSTEM-100']


def a7(t):
    v = 0
    for x in t.split():
        v = (v << 7) + int(x, 16)
    return v


def patch_rows(script):
    root = ET.parse(script).getroot()
    types = {}
    for e in root.findall('structType'):
        types.setdefault(e.findtext('type'), e)

    def leaves(t, base, path):
        e = types[t]
        subs = e.findall('struct')
        if not subs:
            yield path or t, base, e
            return
        for c in subs:
            name = c.findtext('name') or c.findtext('type')
            yield from leaves(c.findtext('type'), base + a7(c.findtext('address')), f'{path}.{name}' if path else name)

    rows = []
    for path, base, e in leaves('patch', 0, ''):
        off = 0
        for v in e.findall('value'):
            vt = v.findtext('type') or ''
            m = re.match(r'int(\d+)x(\d+)$', vt)
            n, bits = (int(m.group(1)), int(m.group(2))) if m else (a7(v.findtext('size') or '00'), 4)
            addrs = [a7(a.text) for a in v.findall('address')]
            o = addrs[0] if addrs else off
            rng = v.findtext('range')
            lo, hi = (int(x) for x in rng.split(',')) if rng else (None, None)
            d = v.findtext('default')
            if vt != 'stringNx4' and v.findtext('name') != 'name':
                rows.append([v.findtext('name'), base + o, n, bits, lo, hi, int(d) if d and re.match(r'-?\d+$', d) else None])
            if not addrs:
                off += n
    return rows


def region0(path):
    d = open(path, 'rb').read()
    flat = [r for t in R0.find_tables(d) for r in t]
    pages, lists, cur, curl = [], {}, None, None
    for r in flat:
        if r['kind'] == 'page':
            cur = [r['name'], []]
            pages.append(cur)
        elif r['kind'] == 'param':
            w = r['w']
            # [OS id, own label, min, max, list, display kind, index on the page]
            cur[1].append([r['id'], r['name'], w[1], w[2], w[5], w[6], w[7]])
        elif r['kind'] == 'list':
            curl = lists.setdefault(r['w'][0], [])
        else:
            curl.append(r['text'])
    m = d.find(b'SYSTEM8_SYNINFO\0')
    name = d[m + 16:m + 32].split(b'\0')[0].decode()
    model, ver = struct.unpack_from('<HH', d, m + 32)
    return name, model, ver, pages, lists


def main():
    out = sys.argv[1]
    data = {}
    for e in ENGINES:
        name, model, ver, pages, lists = region0(os.path.join(ROOT, 're', 'system8', 'images', f'{e}_s1_region0.bin'))
        data[e] = {'name': name, 'model': model, 'version': ver, 'rows': patch_rows(os.path.join(ROOT, 're', 'system8', 'plugins', e, 'Script', 'Script.xml')),
                   'pages': pages, 'lists': lists}
    hdr = ('// Generated by tools/system8/gen_plugouts_js.py from each PLUG-OUT\'s Roland Cloud plugin script (the patch\n'
           '// struct: names, packed offsets, sizes, ranges, defaults) and its region 0 image (pages, OS parameter ids,\n'
           '// own labels, ranges, value lists, SYNINFO model id / version). Do not edit by hand.\n//\n'
           '// ENGINES[name] = {name, model, version, rows: [[script name, packed offset, bytes, bits, min, max, default]],\n'
           '//   pages: [[page, [[OS id, own label, min, max, list, display kind, index]]]], lists: {n: [texts]}}\n\n')
    with open(out, 'w', newline='\n') as f:
        f.write(hdr + 'export const ENGINES = ' + json.dumps(data, separators=(',', ':'), ensure_ascii=False) + ';\n')
    print(out, {k: (v['model'], hex(v['version']), len(v['rows']), len(v['pages'])) for k, v in data.items()})


if __name__ == '__main__':
    main()
